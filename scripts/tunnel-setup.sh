#!/usr/bin/env bash
# Thiết lập Cloudflare Named Tunnel cho radar: <subdomain>.astrq.io.vn -> 127.0.0.1:<port>
#
#   scripts/tunnel-setup.sh                         # radar.astrq.io.vn -> :8000
#   scripts/tunnel-setup.sh --host ten.astrq.io.vn  # đổi subdomain
#   scripts/tunnel-setup.sh --port 8080
#
# Chạy lại bao nhiêu lần cũng được (idempotent): tunnel đã có thì dùng lại, bản ghi DNS
# được trỏ lại đúng tunnel. Named Tunnel có ID cố định nên tên miền KHÔNG phải gán lại
# khi khởi động lại máy hay đổi mạng/IP.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HOST="${ASTRQ_PUBLIC_HOST:-radar.astrq.io.vn}"
PORT="8000"
TUNNEL="astrq-radar"
QUIET=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --host) HOST="${2:?}"; shift ;;
    --port) PORT="${2:?}"; shift ;;
    --name) TUNNEL="${2:?}"; shift ;;
    --quiet) QUIET=1 ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "Tùy chọn không hợp lệ: $1"; exit 1 ;;
  esac
  shift
done

say() { (( QUIET )) || printf '\033[1;36m▸ %s\033[0m\n' "$*"; }
ok()  { (( QUIET )) || printf '\033[1;32m✔ %s\033[0m\n' "$*"; }
die() { printf '\033[1;31m✖ %s\033[0m\n' "$*" >&2; exit 1; }

command -v cloudflared >/dev/null || die "Chưa cài cloudflared"
[[ $HOST == *.astrq.io.vn || $HOST == astrq.io.vn ]] || say "Lưu ý: $HOST không thuộc astrq.io.vn — tên miền đó phải nằm trong cùng tài khoản Cloudflare"

# 1) Đăng nhập (một lần, cần trình duyệt)
CERT="${TUNNEL_ORIGIN_CERT:-$HOME/.cloudflared/cert.pem}"
if [[ ! -f $CERT ]]; then
  say "Chưa đăng nhập Cloudflare — mở trình duyệt để cấp quyền cho tên miền astrq.io.vn…"
  cloudflared tunnel login
  [[ -f $CERT ]] || die "Đăng nhập chưa xong (không thấy $CERT)"
fi
ok "Đã đăng nhập Cloudflare"

# 2) Tạo tunnel nếu chưa có
tunnel_id() {
  cloudflared tunnel list --name "$TUNNEL" -o json 2>/dev/null \
    | python3 -c 'import json,sys
d=json.load(sys.stdin) or []
alive=[t for t in d if not t.get("deleted_at") or t["deleted_at"].startswith("0001")]
print(alive[0]["id"] if alive else "")'
}
ID="$(tunnel_id)"
if [[ -z $ID ]]; then
  say "Tạo tunnel '$TUNNEL'…"
  cloudflared tunnel create "$TUNNEL" >/dev/null
  ID="$(tunnel_id)"
  [[ -n $ID ]] || die "Không tạo được tunnel"
fi
CRED="$HOME/.cloudflared/$ID.json"
[[ -f $CRED ]] || die "Thiếu file credentials $CRED (tunnel tạo ở máy khác?). Xóa tunnel cũ trên dashboard Cloudflare rồi chạy lại."
ok "Tunnel '$TUNNEL' sẵn sàng"

# 3) Trỏ tên miền vào tunnel (CNAME -> <id>.cfargotunnel.com), sửa lại nếu đang trỏ chỗ khác
say "Trỏ $HOST vào tunnel…"
cloudflared tunnel route dns --overwrite-dns "$TUNNEL" "$HOST" >/dev/null 2>&1 \
  || die "Không tạo được bản ghi DNS cho $HOST (tên miền có nằm trong tài khoản Cloudflare đã đăng nhập không?)"
ok "DNS: $HOST → tunnel $TUNNEL"

# 4) Cấu hình: chỉ phục vụ đúng hostname này, mọi thứ khác trả 404
mkdir -p "$ROOT/.tunnel"
CFG="$ROOT/.tunnel/config.yml"
cat > "$CFG" <<EOF
# Generated by scripts/tunnel-setup.sh — do not edit by hand.
tunnel: $ID
credentials-file: $CRED
ingress:
  - hostname: $HOST
    service: http://127.0.0.1:$PORT
  - service: http_status:404
EOF
cloudflared tunnel --config "$CFG" ingress validate >/dev/null || die "Cấu hình tunnel không hợp lệ"
ok "Cấu hình: $CFG"

(( QUIET )) || cat <<EOF

Xong. Chạy radar công khai:   ./run.sh --public
Địa chỉ:                     https://$HOST

⚠ Dashboard CHƯA có đăng nhập. Hãy bật Cloudflare Access trước khi chia sẻ link:
  Cloudflare dashboard → Zero Trust → Access → Applications → Add an application
  → Self-hosted → domain: $HOST → policy: Allow, Include: Emails = <email của bạn>
EOF
